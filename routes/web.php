<?php

use App\Http\Controllers\CustomerController;
use App\Http\Controllers\PageController;
use App\Http\Controllers\ProfileController;
use App\Http\Controllers\UserController;
use Illuminate\Support\Facades\Route;

// Public pages
Route::get('/', [PageController::class, 'landing'])->name('landing');
Route::get('/about', [PageController::class, 'about'])->name('about');

// Everything inside this group requires a logged-in user.
// Guests are redirected to the login page by the auth middleware.
Route::middleware('auth')->group(function () {
    Route::get('/dashboard', function () {
        return view('dashboard');
    })->name('dashboard');

    // One line each replaces the manual customer and user routes:
    // index, create, store, show, edit, update, destroy.
    Route::resource('customers', CustomerController::class);
    Route::resource('users', UserController::class);

    // Profile routes generated by Breeze (its navigation links to them).
    Route::get('/profile', [ProfileController::class, 'edit'])->name('profile.edit');
    Route::patch('/profile', [ProfileController::class, 'update'])->name('profile.update');
    Route::delete('/profile', [ProfileController::class, 'destroy'])->name('profile.destroy');
});

// Login, registration, password reset and logout routes added by Breeze.
require __DIR__ . '/auth.php';
